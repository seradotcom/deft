/**
 * Expected business results the CALLER must hear about ("no such member" is an
 * answer, not a crash). Detection patterns turn matching step failures into a
 * declared outcome instead of a failure.
 */
export const BusinessOutcome = z.object({
  code: z.string().regex(/^[A-Z][A-Z0-9_]+$/),
  description: z.string().min(3),
  detect: z.object({
    duringStepId: z.string().optional(),
    pageTextContains: z.string().optional(),
    dialogTextContains: z.string().optional(),
    urlGlob: z.string().optional(),
  }).refine((d) => Object.values(d).some(Boolean), { message: 'detect needs at least one pattern' }),
  returnsToCaller: z.record(z.string(), z.unknown()).default({}),
});
export type BusinessOutcome = z.infer<typeof BusinessOutcome>;

export const RiskPolicy = z
  .object({
    /** What to do when a risky (irreversible) step is reached during unattended replay. */
    onRiskyStep: z.enum(['require_approval', 'allow']).default('require_approval'),
    rationale: z.string().optional(),
  })
  .default({ onRiskyStep: 'require_approval' });

/** Tenant-specific overlay for artifacts shared across institutions. */
export const Variant = z.object({
  id: z.string().min(1),
  match: z.object({ tenantId: z.string().min(1) }),
  /** Flat-key patches, e.g. "steps[s4].target.primary.name": "Find Member". */
  patches: z.record(z.string(), z.unknown()).default({}),
  notes: z.string().optional(),
});
export type Variant = z.infer<typeof Variant>;

export const Provenance = z.object({
  discoveredFromRunId: z.string().optional(),
  /** Null/absent for operator-authored capabilities (no planner involved). */
  plannerModel: z.string().nullable().optional(),
  recordedAt: z.string().datetime().optional(),
  stepCount: z.number().int().nonnegative().optional(),
  validation: z
    .object({
      lastReplayAt: z.string().datetime().nullable().default(null),
      lastReplayStatus: z.enum(['SUCCESS', 'BUSINESS_OUTCOME', 'FAILED']).nullable().default(null),
      replaySuccessCount: z.number().int().nonnegative().default(0),
      replayFailureCount: z.number().int().nonnegative().default(0),
    })
    .default({
      lastReplayAt: null,
      lastReplayStatus: null,
      replaySuccessCount: 0,
      replayFailureCount: 0,
    }),
});
export type Provenance = z.infer<typeof Provenance>;

export const CapabilityArtifactSchema = z.object({
  schemaVersion: z.literal('1'),
  kind: z.literal('Capability'),
  metadata: z.object({
    id: z.string().regex(/^[a-z0-9]+([.-][a-z0-9]+)*\.[a-z0-9]+([.-][a-z0-9]+)*$/, 'id must be <appfamily>.<capability>'),
    name: z.string().min(3),
    description: z.string().min(10),
    version: z.string().regex(/^\d+\.\d+\.\d+$/),
    status: z.enum(['draft', 'approved', 'needs-review', 'deprecated']).default('draft'),
    createdAt: z.string().datetime(),
    updatedAt: z.string().datetime(),
  }),
  target: z.object({
    appFamily: z.string().min(1),
    surfaceType: z.enum(['web-modern', 'web-legacy', 'desktop']),
    entryUrlTemplate: z.string().min(1),
    variants: z.array(Variant).default([]),
  }),
  inputs: z.record(z.string(), z.unknown()), // JSON Schema (draft 2020-12)
  outputs: z.record(z.string(), z.unknown()), // JSON Schema
  environmentBindings: z.record(z.string(), EnvBinding).default({}),
  steps: z.array(Step).min(1),
  /**
   * Deterministic authentication phase, executed by the ENGINE before the
   * planner ever observes the surface (discovery) and before capability steps
   * (replay). Credential values live only in environment bindings — they are
   * resolved at runtime and NEVER enter model context.
   */
  authPhase: z.object({ steps: z.array(Step).min(1) }).optional(),
  businessOutcomes: z.array(BusinessOutcome).default([]),
  /** Named, shared recovery action chains referenced by steps via chainRef. */
  recoveryChains: z.record(z.string(), z.array(RecoverAction)).optional(),
  successCondition: z.object({
    allOf: z.array(Check).min(1),
  }),
  riskPolicy: RiskPolicy,
  redaction: z.object({
    sensitiveInputNames: z.array(z.string()).default([]),
    notes: z.string().default(''),
  }),
  provenance: Provenance,
});
export type CapabilityArtifact = z.infer<typeof CapabilityArtifactSchema>;

// ---------------------------------------------------------------------------
// Replay result contract — the three-way outcome distinction lives HERE.
// ---------------------------------------------------------------------------

export const ReplayStatus = z.enum(['SUCCESS', 'BUSINESS_OUTCOME', 'FAILED']);
export type ReplayStatus = z.infer<typeof ReplayStatus>;

export interface StepTimelineEntry {
  stepId: string;
  intent: string;
  phase: 'wait' | 'locate' | 'act' | 'verify' | 'recover';
  ok: boolean;
  ms: number;
  detail?: string;
  degraded?: boolean;
  recovered?: boolean;
}

export interface FailureDetail {
  stepId: string;
  phase: NonNullable<StepTimelineEntry['phase']>;
  errorClass: string;
  expected: string;
  observed: string;
  evidenceRefs: string[]; // screenshot/log refs under /evidence
}

export interface EscalationInfo {
  interventionId: string;
  reason: string;
  resumedByHuman: boolean;
  /** Audit samples captured while the human held the lease. */
  humanSamplesCaptured: number;
  /** Samples that differed from the previous one — evidence of REAL state
   *  change under human control (not N identical screenshots). */
  humanStateChanges: number;
}

export interface ReplayResult {
  runId: string;
  capabilityId: string;
  capabilityVersion: string;
  /** sha256 of the exact artifact bytes this run executed — audit trail. */
  artifactSha256?: string;
  status: ReplayStatus;
  outputs?: Record<string, unknown>;
  businessOutcome?: { code: string; description: string; returnsToCaller: Record<string, unknown> };
  escalation?: EscalationInfo;
  failure?: FailureDetail;
  timeline: StepTimelineEntry[];
  /** Steps resolved via last-resort coordinate targeting — drift signal. */
  degradedSteps: string[];
  startedAt: string;
  finishedAt: string;
}







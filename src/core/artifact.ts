export const Check = z.discriminatedUnion('assert', [
  z.object({ assert: z.literal('urlMatchesGlob'), pattern: z.string().min(1) }).strict(),
  z.object({ assert: z.literal('elementVisible'), target: TargetDescriptor, timeoutMs: z.number().int().positive().default(10000) }).strict(),
  z.object({ assert: z.literal('elementTextContains'), target: TargetDescriptor, text: z.string().min(1), timeoutMs: z.number().int().positive().default(10000) }).strict(),
  z.object({ assert: z.literal('pageTextContains'), text: z.string().min(1) }).strict(),
]);
export type Check = z.infer<typeof Check>;

/**
 * Environment bindings resolve templates like {{env.username}} or {{baseUrl}}
 * WITHOUT ever persisting secret material inside the artifact.
 */
export const EnvBinding = z.discriminatedUnion('source', [
  z.object({ source: z.literal('literal'), value: z.string() }).strict(),
  z.object({ source: z.literal('envVar'), name: z.string().min(1), sensitive: z.boolean().default(false) }).strict(),
]);
export type EnvBinding = z.infer<typeof EnvBinding>;

/**
 * Bounded, auditable recovery for legitimate runtime conditions.
 * A rule fires at most maxAttempts times per run; every attempt lands in
 * evidence. Actions form a short chain (e.g. session-expired → re-login).
 */
export const RecoverAction = z.discriminatedUnion('action', [
  z.object({ action: z.literal('navigate'), urlTemplate: z.string().min(1), riskClass: z.enum(['safe', 'risky']), idempotent: z.boolean(), expectsDialog: z.boolean() }).strict(),
  z.object({ action: z.literal('click'), target: TargetDescriptor, riskClass: z.enum(['safe', 'risky']), idempotent: z.boolean(), expectsDialog: z.boolean() }).strict(),
  z.object({ action: z.literal('fill'), target: TargetDescriptor, valueTemplate: z.string().min(1), riskClass: z.enum(['safe', 'risky']), idempotent: z.boolean(), expectsDialog: z.boolean() }).strict(),
  z.object({ action: z.literal('select'), target: TargetDescriptor, optionTextTemplate: z.string().min(1), riskClass: z.enum(['safe', 'risky']), idempotent: z.boolean(), expectsDialog: z.boolean() }).strict(),
  z.object({ action: z.literal('wait'), durationMs: z.number().int().positive().max(30000), riskClass: z.enum(['safe', 'risky']), idempotent: z.boolean(), expectsDialog: z.boolean() }).strict(),
  /** Navigate the failed step's frame (or top) back to step.pageUrl. */
  z.object({ action: z.literal('gotoStepPage'), riskClass: z.enum(['safe', 'risky']), idempotent: z.boolean(), expectsDialog: z.boolean() }).strict(),
]);
export type RecoverAction = z.infer<typeof RecoverAction>;

export const RecoverRule = z.object({
  description: z.string().min(3),
  // Only conditions the engine actually evaluates — schema honesty over breadth.
  when: z
    .object({
      redirectedToGlob: z.string().optional(),
      errorClass: z.string().optional(),
    })
    .strict().refine((w) => Object.values(w).some(Boolean), { message: 'when needs at least one condition' }),
  do: z.array(RecoverAction).min(1).max(5),
  maxAttempts: z.number().int().min(1).max(3).default(1),
}).strict();
/**
 * A rule may either inline its action chain or reference a named chain in
 * artifact.recoveryChains — shared recovery logic without per-step bloat.
 */
export const RecoverSpec = z.union([
  RecoverRule,
  z.object({ chainRef: z.string().min(1), description: z.string().optional() }).strict(),
]);
export type RecoverSpec = z.infer<typeof RecoverSpec>;


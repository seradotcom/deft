export const StepAction = z.enum([
  'navigate',
  'click',
  'fill',
  'select',
  'press',
  'scroll',
  'wait',
  'extract',
  'check',
]);
export type StepAction = z.infer<typeof StepAction>;

/** Relational extraction from hostile tables — robust to row reordering. */
export const TableExtract = z.object({
  strategy: z.literal('tableCell'),
  scope: z
    .object({
      framePath: z.array(z.string()).default([]),
      container: LocatorSpec.optional(),
    })
    .strict().default({ framePath: [] }),
  rowMatch: z.object({
    columnHeader: z.string().min(1),
    equalsTemplate: z.string().optional(),
    containsTemplate: z.string().optional(),
  }).strict(),
  columnHeader: z.string().min(1),
}).strict();

export const TextExtract = z.object({
  strategy: z.literal('text'),
  target: TargetDescriptor,
  /** First capture group is returned when present. */
  regexWithGroups: z.string().optional(),
}).strict();
export type TableExtract = z.infer<typeof TableExtract>;
export type TextExtract = z.infer<typeof TextExtract>;

export const Step = z.object({
  id: z.string().regex(/^[a-z0-9_.-]+$/i).min(2),
  /** Human-readable intent — makes the artifact reviewable without code reading. */
  intent: z.string().min(3),
  action: StepAction,
  target: TargetDescriptor.optional(),
  /** Template string; may reference {{inputs.*}}, {{env.*}}, {{target.*}}, prior outputs {{outputs.*}}. */
  valueTemplate: z.string().optional(),
  /** Page URL (template) where this step executes — lets recovery chains
   *  return the flow to the right page after a mid-flow re-login. */
  pageUrl: z.string().optional(),
  selectOptionText: z.string().optional(),
  keyCombo: z.string().optional(),
  /** Explicit wait duration used by guarded recovery wait actions. */
  waitDurationMs: z.number().int().positive().max(30000).optional(),
  scrollDirection: z.enum(['up', 'down']).optional(),
  postCheck: Check.optional(),
  /**
   * Replay-safety semantics. Non-idempotent steps (submits, transfers) are
   * NEVER re-executed by recovery fast-forward — re-running them could
   * duplicate financial side effects.
   */
  idempotent: z.boolean().default(true),
  /**
   * Declares that this step EXPECTS a native dialog (confirm/alert) and the
   * engine should ACCEPT it. Default: all dialogs are DISMISSED (safe default
   * — infrastructure never auto-accepts an unexpected irreversible confirm).
   */
  expectsDialog: z.boolean().default(false),
  recoverableErrors: z.array(RecoverSpec).max(4).default([]),
  riskClass: z.enum(['safe', 'risky']).default('safe'),
  // extract-only fields:
  outputKey: z.string().optional(),
  extract: z.union([TableExtract, TextExtract]).optional(),
}).strict();
export type Step = z.infer<typeof Step>;


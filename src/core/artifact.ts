export const ReplayStatus = z.enum(['SUCCESS', 'BUSINESS_OUTCOME', 'FAILED']);
export type ReplayStatus = z.infer<typeof ReplayStatus>;

export interface StepTimelineEntry {
  stepId: string;
  intent: string;
  phase: 'wait' | 'locate' | 'act' | 'verify' | 'recover';
  ok: boolean;
  ms: number;
  detail?: string;
  degraded?: boolean;
  recovered?: boolean;
}

export interface FailureDetail {
  stepId: string;
  phase: NonNullable<StepTimelineEntry['phase']>;
  errorClass: string;
  expected: string;
  observed: string;
  evidenceRefs: string[]; // screenshot/log refs under /evidence
}

export interface EscalationInfo {
  interventionId: string;
  reason: string;
  resumedByHuman: boolean;
  /** Audit samples captured while the human held the lease. */
  humanSamplesCaptured: number;
  /** Samples that differed from the previous one — evidence of REAL state
   *  change under human control (not N identical screenshots). */
  humanStateChanges: number;
}

export interface ReplayResult {
  runId: string;
  capabilityId: string;
  capabilityVersion: string;
  /** sha256 of the exact artifact bytes this run executed — audit trail. */
  artifactSha256?: string;
  /** Relative evidence-bundle reference to the exact executed definition bytes. */
  artifactDefinitionRef?: string;
  status: ReplayStatus;
  outputs?: Record<string, unknown>;
  businessOutcome?: { code: string; description: string; returnsToCaller: Record<string, unknown> };
  escalation?: EscalationInfo;
  failure?: FailureDetail;
  timeline: StepTimelineEntry[];
  /** Steps resolved via last-resort coordinate targeting — drift signal. */
  degradedSteps: string[];
  startedAt: string;
  finishedAt: string;
}







type JsonSchemaRecord = Record<string, unknown>;

/** Output JSON Schema with fail-closed object contracts at every depth. */
export const OutputSchema = z.record(z.string(), z.unknown()).superRefine((schema, ctx) => {
  const unsupportedKeywords = [
    '$ref', '$defs', 'definitions', 'oneOf', 'anyOf', 'allOf', 'not', 'if', 'then', 'else',
    'prefixItems', 'contains', 'dependentSchemas', 'patternProperties', 'unevaluatedProperties',
  ];
  const visit = (node: unknown, path: (string | number)[], ancestors: Set<object>): void => {
    if (!node || typeof node !== 'object' || Array.isArray(node)) return;
    const record = node as JsonSchemaRecord;
    if (ancestors.has(record)) {
      ctx.addIssue({ code: 'custom', path, message: 'cyclic output schema is not supported' });
      return;
    }
    const nextAncestors = new Set(ancestors);
    nextAncestors.add(record);

    const structuralKeys = ['properties', 'required', 'additionalProperties'];
    if (!('type' in record)) {
      ctx.addIssue({ code: 'custom', path, message: 'output schemas require an explicit type' });
    } else if (structuralKeys.some((key) => key in record) && record.type !== 'object') {
      ctx.addIssue({ code: 'custom', path, message: 'properties/required/additionalProperties require type object' });
    }

    for (const keyword of unsupportedKeywords) {
      if (Object.prototype.hasOwnProperty.call(record, keyword)) {
        ctx.addIssue({ code: 'custom', path: [...path, keyword], message: `unsupported output schema keyword: ${keyword}` });
      }
    }

    if (record.type === 'object') {
      const properties = record.properties;
      if (!properties || typeof properties !== 'object' || Array.isArray(properties)) {
        ctx.addIssue({ code: 'custom', path, message: 'object output schemas require properties' });
      } else {
        const propertyKeys = Object.keys(properties as JsonSchemaRecord).sort();
        const required = Array.isArray(record.required)
          ? record.required.filter((key): key is string => typeof key === 'string')
          : [];
        if (required.length !== new Set(required).size || [...required].sort().join('\0') !== propertyKeys.join('\0')) {
          ctx.addIssue({ code: 'custom', path: [...path, 'required'], message: 'required must exactly cover output properties' });
        }
        if (record.additionalProperties !== false) {
          ctx.addIssue({ code: 'custom', path: [...path, 'additionalProperties'], message: 'additionalProperties must be false' });
        }
        for (const [key, child] of Object.entries(properties as JsonSchemaRecord)) {
          visit(child, [...path, 'properties', key], nextAncestors);
        }
      }
    }

    if (record.type === 'array') {
      if (!('items' in record)) {
        ctx.addIssue({ code: 'custom', path, message: 'array output schemas require items' });
      } else {
        visit(record.items, [...path, 'items'], nextAncestors);
      }
    }
  };

  visit(schema, [], new Set());
});
export type OutputSchema = z.infer<typeof OutputSchema>;

export const CapabilityArtifactSchema = z.object({
  schemaVersion: z.literal('1'),
  kind: z.literal('Capability'),
  metadata: z.object({
    id: z.string().regex(/^[a-z0-9]+([.-][a-z0-9]+)*\.[a-z0-9]+([.-][a-z0-9]+)*$/, 'id must be <appfamily>.<capability>'),
    name: z.string().min(3),
    description: z.string().min(10),
    version: z.string().regex(/^\d+\.\d+\.\d+$/),
    status: z.enum(['draft', 'approved', 'needs-review', 'deprecated']).default('draft'),
    createdAt: z.string().datetime(),
    updatedAt: z.string().datetime(),
  }).strict(),
  target: z.object({
    appFamily: z.string().min(1),
    surfaceType: z.enum(['web-modern', 'web-legacy', 'desktop']),
    entryUrlTemplate: z.string().min(1),
    variants: z.array(Variant).default([]),
  }).strict(),
  inputs: z.record(z.string(), z.unknown()), // JSON Schema (draft 2020-12)
  outputs: OutputSchema,
  environmentBindings: z.record(z.string(), EnvBinding).default({}),
  steps: z.array(Step).min(1),
  /**
   * Deterministic authentication phase, executed by the ENGINE before the
   * planner ever observes the surface (discovery) and before capability steps
   * (replay). Credential values live only in environment bindings — they are
   * resolved at runtime and NEVER enter model context.
   */
  authPhase: z.object({ steps: z.array(Step).min(1) }).strict().optional(),
  businessOutcomes: z.array(BusinessOutcome).default([]),
  /** Named, shared recovery action chains referenced by steps via chainRef. */
  recoveryChains: z.record(z.string(), z.array(RecoverAction)).optional(),
  successCondition: z.object({
    allOf: z.array(Check).min(1),
  }).strict(),
  riskPolicy: RiskPolicy,
  redaction: z.object({
    sensitiveInputNames: z.array(z.string()).default([]),
    notes: z.string().default(''),
  }).strict(),
  provenance: Provenance,
}).strict().superRefine((artifact, ctx) => {
  const outputSchema = artifact.outputs as Record<string, unknown>;
  const properties = outputSchema.type === 'object' && outputSchema.properties && typeof outputSchema.properties === 'object'
    ? new Set(Object.keys(outputSchema.properties as Record<string, unknown>))
    : new Set<string>();
  for (const step of [...(artifact.authPhase?.steps ?? []), ...artifact.steps]) {
    if (step.action === 'extract' && !step.extract) ctx.addIssue({ code: 'custom', path: ['steps', step.id, 'extract'], message: 'extract steps require extract specification' });
    if (step.action !== 'extract' && step.extract) ctx.addIssue({ code: 'custom', path: ['steps', step.id, 'extract'], message: 'extract specification is only valid on extract steps' });
    if (step.action === 'extract' && !step.outputKey) ctx.addIssue({ code: 'custom', path: ['steps', step.id, 'outputKey'], message: 'extract steps require outputKey' });
    if (step.action !== 'extract' && step.outputKey) ctx.addIssue({ code: 'custom', path: ['steps', step.id, 'outputKey'], message: 'outputKey is only valid on extract steps' });
    if (step.outputKey && !properties.has(step.outputKey)) ctx.addIssue({ code: 'custom', path: ['steps', step.id, 'outputKey'], message: 'outputKey must be declared in outputs.properties' });
  }
});
export type CapabilityArtifact = z.infer<typeof CapabilityArtifactSchema>;

/** Normalize compiler-proposed object output contracts before artifact parsing. */
export function normalizeOutputSchema(schema: Record<string, unknown>): Record<string, unknown> {
  const normalize = (node: unknown): unknown => {
    if (!node || typeof node !== 'object' || Array.isArray(node)) return node;
    const current = node as Record<string, unknown>;
    const normalized = { ...current };
    if (current.type === 'object' && current.properties && typeof current.properties === 'object' && !Array.isArray(current.properties)) {
      const properties = Object.fromEntries(
        Object.entries(current.properties as Record<string, unknown>).map(([key, child]) => [key, normalize(child)])
      );
      const existingRequired = Array.isArray(current.required)
        ? current.required.filter((key): key is string => typeof key === 'string')
        : [];
      normalized.properties = properties;
      normalized.required = [...new Set([...existingRequired, ...Object.keys(properties)])];
      normalized.additionalProperties = false;
    } else if (current.type === 'array' && 'items' in current) {
      normalized.items = normalize(current.items);
    }
    return normalized;
  };
  return normalize(schema) as Record<string, unknown>;
}

